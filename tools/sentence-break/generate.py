"""Generate the Sentence_Break table of Intl.Segmenter from Unicode 17.0.0 SentenceBreakProperty.txt.

Usage: python3 tools/sentence-break/generate.py /path/to/SentenceBreakProperty.txt
Source: https://www.unicode.org/Public/17.0.0/ucd/auxiliary/SentenceBreakProperty.txt

Writes Jint/Native/Intl/SentenceBreaker.Data.cs. Run it from the repository root. The build never runs it.
"""
import hashlib
import pathlib
import re
import sys

PINNED_HEADER = '# SentenceBreakProperty-17.0.0.txt'
PINNED_SHA256 = '871c0c985ad95125e25b302414065a10839d068970bceb383ecec138f22a0a18'

# The order is the order of SentenceBreaker.SentenceClass. CR and LF are not in the table (the breaker reads them
# before it classifies a code point), Sep is the ParaSep of the rules, Format is treated as Extend by SB5.
CLASSES = ['Other', 'ParaSep', 'Extend', 'Sp', 'Lower', 'Upper', 'OLetter', 'Numeric', 'ATerm', 'SContinue', 'STerm', 'Close']
PROPERTY_TO_CLASS = {
    'CR': 'ParaSep', 'LF': 'ParaSep', 'Sep': 'ParaSep',
    'Extend': 'Extend', 'Format': 'Extend',
    'Sp': 'Sp', 'Lower': 'Lower', 'Upper': 'Upper', 'OLetter': 'OLetter', 'Numeric': 'Numeric',
    'ATerm': 'ATerm', 'SContinue': 'SContinue', 'STerm': 'STerm', 'Close': 'Close',
}

raw = pathlib.Path(sys.argv[1]).read_bytes()
digest = hashlib.sha256(raw).hexdigest()
if digest != PINNED_SHA256:
    sys.exit(f'{sys.argv[1]} is not the pinned file: SHA-256 {digest}, expected {PINNED_SHA256}')
source = raw.decode('utf-8')
assert source.startswith(PINNED_HEADER)

values = bytearray(0x110000)  # everything not listed is Other (the @missing line of the file)
seen = set()
for match in re.finditer(r'^([0-9A-F]+)(?:\.\.([0-9A-F]+))?\s*;\s*(\w+)', source, re.M):
    start = int(match.group(1), 16)
    end = int(match.group(2) or match.group(1), 16)
    name = PROPERTY_TO_CLASS[match.group(3)]
    seen.add(match.group(3))
    values[start:end + 1] = bytes([CLASSES.index(name)]) * (end - start + 1)
assert seen == set(PROPERTY_TO_CLASS), seen ^ set(PROPERTY_TO_CLASS)

# One entry per run of one class: the start of the run in the high bits, the class in the low four.
entries = [i << 4 | value for i, value in enumerate(values) if i == 0 or value != values[i - 1]]

output = '''// <auto-generated>
// Generated by tools/sentence-break/generate.py from Unicode 17.0.0 SentenceBreakProperty.txt.
// Do not edit by hand: change the generator and run it again (see tools/sentence-break/README.md).
// Unicode data: https://www.unicode.org/license.txt
// </auto-generated>
namespace Jint.Native.Intl;

internal static partial class SentenceBreaker
{
    // The Sentence_Break property (https://www.unicode.org/reports/tr29/#Sentence_Break_Values) of every code point,
    // as runs: each entry is the first code point of a run shifted left by four, with the SentenceClass of the whole
    // run in the low four bits. A run lasts until the start of the next entry. CR and LF are ParaSep, and Format is
    // Extend, as SB5 treats it.
    // It is an array, not a span property, because a span over a collection expression allocates on every read where
    // the runtime has no RuntimeHelpers.CreateSpan, which is net472 and netstandard2.0.
    private static readonly int[] _runs =
    [
'''
for i in range(0, len(entries), 8):
    output += '        ' + ', '.join(f'0x{x:X}' for x in entries[i:i + 8]) + ',\n'
output += '''    ];
}
'''
pathlib.Path('Jint/Native/Intl/SentenceBreaker.Data.cs').write_text(output, encoding='utf-8', newline='\n')
print(f'{len(entries)} runs')
