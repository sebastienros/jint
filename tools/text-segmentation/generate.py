"""Generate the Unicode 17.0.0 tables of Intl.Segmenter's grapheme, sentence and word granularities.

Usage: python3 tools/text-segmentation/generate.py /path/to/ucd
Source: https://www.unicode.org/Public/17.0.0/ucd/, the files of PINNED below, all in the one directory given.

Writes Jint/Native/Intl/GraphemeBreaker.Data.cs, Jint/Native/Intl/SentenceBreaker.Data.cs and
Jint/Native/Intl/WordBreaker.Data.cs. Run it from the repository root. The build never runs it.
"""
import hashlib
import pathlib
import re
import sys

# Every input, with the first line and the SHA-256 of the Unicode 17.0.0 file. Moving to another version means changing
# all of them on purpose.
PINNED = {
    'SentenceBreakProperty.txt': ('# SentenceBreakProperty-17.0.0.txt', '871c0c985ad95125e25b302414065a10839d068970bceb383ecec138f22a0a18'),
    'WordBreakProperty.txt': ('# WordBreakProperty-17.0.0.txt', '72274cac1e6b919507db35655c3e175aa27274668a1ece95c28d2069f2ad9852'),
    'emoji-data.txt': ('# emoji-data.txt', '2cb2bb9455cda83e8481541ecf5b6dfda66a3bb89efa3fa7c5297eccf607b72b'),
    'Scripts.txt': ('# Scripts-17.0.0.txt', '9f5e50d3abaee7d6ce09480f325c706f485ae3240912527e651954d2d6b035bf'),
    'PropList.txt': ('# PropList-17.0.0.txt', '130dcddcaadaf071008bdfce1e7743e04fdfbc910886f017d9f9ac931d8c64dd'),
    'LineBreak.txt': ('# LineBreak-17.0.0.txt', 'e6a18fa91f8f6a6f8e534b1d3f128c21ada45bfe152eb6b1bcc5e15fd8ac92e6'),
    'GraphemeBreakProperty.txt': ('# GraphemeBreakProperty-17.0.0.txt', 'd6b51d1d2ae5c33b451b7ed994b48f1f4dc62b2272a5831e7fd418514a6bae89'),
    'DerivedCoreProperties.txt': ('# DerivedCoreProperties-17.0.0.txt', '24c7fed1195c482faaefd5c1e7eb821c5ee1fb6de07ecdbaa64b56a99da22c08'),
}

UCD = pathlib.Path(sys.argv[1])


def read(name):
    header, pinned = PINNED[name]
    raw = (UCD / name).read_bytes()
    digest = hashlib.sha256(raw).hexdigest()
    if digest != pinned:
        sys.exit(f'{UCD / name} is not the pinned file: SHA-256 {digest}, expected {pinned}')
    source = raw.decode('utf-8')
    assert source.startswith(header), name
    return source


def entries(name):
    """(first, last, value) for every data line of a UCD file, in file order."""
    for match in re.finditer(r'^([0-9A-F]+)(?:\.\.([0-9A-F]+))?\s*;\s*(\w+)', read(name), re.M):
        yield int(match.group(1), 16), int(match.group(2) or match.group(1), 16), match.group(3)


def code_points(name, value):
    """The set of code points a UCD file gives the value, as a bytearray of 0 and 1."""
    result = bytearray(0x110000)
    for first, last, found in entries(name):
        if found == value:
            result[first:last + 1] = b'\x01' * (last - first + 1)
    return result


def runs(values, shift):
    """One entry per run of one value: the first code point of the run shifted left, the value in the low bits."""
    return [i << shift | value for i, value in enumerate(values) if i == 0 or value != values[i - 1]]


def write(source_names, class_name, comment, entries_):
    output = f'''// <auto-generated>
// Generated by tools/text-segmentation/generate.py from Unicode 17.0.0 {source_names}.
// Do not edit by hand: change the generator and run it again (see tools/text-segmentation/README.md).
// Unicode data: https://www.unicode.org/license.txt
// </auto-generated>
namespace Jint.Native.Intl;

internal static partial class {class_name}
{{
{comment}
    // It is an array, not a span property, because a span over a collection expression allocates on every read where
    // the runtime has no RuntimeHelpers.CreateSpan, which is net472 and netstandard2.0.
    private static readonly int[] _runs =
    [
'''
    for i in range(0, len(entries_), 8):
        output += '        ' + ', '.join(f'0x{x:X}' for x in entries_[i:i + 8]) + ',\n'
    output += '    ];\n'
    return output


def ascii_table(values):
    """The properties of the 128 ASCII characters, as the body of a ReadOnlySpan<byte> property."""
    output = ''
    for i in range(0, 0x80, 16):
        output += '        ' + ', '.join(f'0x{x:02X}' for x in values[i:i + 16]) + ',\n'
    return output


def sentence():
    # The order is the order of SentenceBreaker.SentenceClass. CR, LF and Sep are the ParaSep of the rules, Format is
    # treated as Extend by SB5.
    classes = ['Other', 'ParaSep', 'Extend', 'Sp', 'Lower', 'Upper', 'OLetter', 'Numeric', 'ATerm', 'SContinue', 'STerm', 'Close']
    property_to_class = {
        'CR': 'ParaSep', 'LF': 'ParaSep', 'Sep': 'ParaSep',
        'Extend': 'Extend', 'Format': 'Extend',
        'Sp': 'Sp', 'Lower': 'Lower', 'Upper': 'Upper', 'OLetter': 'OLetter', 'Numeric': 'Numeric',
        'ATerm': 'ATerm', 'SContinue': 'SContinue', 'STerm': 'STerm', 'Close': 'Close',
    }

    values = bytearray(0x110000)  # everything not listed is Other (the @missing line of the file)
    seen = set()
    for first, last, name in entries('SentenceBreakProperty.txt'):
        seen.add(name)
        values[first:last + 1] = bytes([classes.index(property_to_class[name])]) * (last - first + 1)
    assert seen == set(property_to_class), seen ^ set(property_to_class)

    result = runs(values, 4)
    output = write('SentenceBreakProperty.txt', 'SentenceBreaker', '''\
    // The Sentence_Break property (https://www.unicode.org/reports/tr29/#Sentence_Break_Values) of every code point,
    // as runs: each entry is the first code point of a run shifted left by four, with the SentenceClass of the whole
    // run in the low four bits. A run lasts until the start of the next entry. CR and LF are ParaSep, and Format is
    // Extend, as SB5 treats it.''', result)
    output += '}\n'
    pathlib.Path('Jint/Native/Intl/SentenceBreaker.Data.cs').write_text(output, encoding='utf-8', newline='\n')
    print(f'Sentence_Break: {len(result)} runs')


# The order is the order of WordBreaker.WordClass, chosen so that the groups the rules test are ranges: the line
# breaks, the characters WB4 ignores, and AHLetter.
WORD_CLASSES = [
    'Other', 'CR', 'LF', 'Newline', 'Extend', 'Format', 'ZWJ', 'ALetter', 'HebrewLetter', 'Numeric', 'Katakana',
    'ExtendNumLet', 'MidLetter', 'MidNumLet', 'SingleQuote', 'MidNum', 'DoubleQuote', 'RegionalIndicator', 'WSegSpace',
    'HangulSyllable',
]
WORD_BREAK_TO_CLASS = {
    'CR': 'CR', 'LF': 'LF', 'Newline': 'Newline', 'Extend': 'Extend', 'Format': 'Format', 'ZWJ': 'ZWJ',
    'ALetter': 'ALetter', 'Hebrew_Letter': 'HebrewLetter', 'Numeric': 'Numeric', 'Katakana': 'Katakana',
    'ExtendNumLet': 'ExtendNumLet', 'MidLetter': 'MidLetter', 'MidNumLet': 'MidNumLet', 'Single_Quote': 'SingleQuote',
    'MidNum': 'MidNum', 'Double_Quote': 'DoubleQuote', 'Regional_Indicator': 'RegionalIndicator', 'WSegSpace': 'WSegSpace',
}
# The flags of WordBreaker, above the five bits of the class.
EXTENDED_PICTOGRAPHIC = 0x20
KANA_KANJI = 0x40
IDEOGRAPHIC_OR_HIRAGANA = 0x80


def word():
    word_break = bytearray(0x110000)  # everything not listed is Other (the @missing line of the file)
    seen = set()
    for first, last, name in entries('WordBreakProperty.txt'):
        seen.add(name)
        word_break[first:last + 1] = bytes([WORD_CLASSES.index(WORD_BREAK_TO_CLASS[name])]) * (last - first + 1)
    assert seen == set(WORD_BREAK_TO_CLASS), seen ^ set(WORD_BREAK_TO_CLASS)

    extended_pictographic = code_points('emoji-data.txt', 'Extended_Pictographic')
    han = code_points('Scripts.txt', 'Han')
    hiragana = code_points('Scripts.txt', 'Hiragana')
    ideographic = code_points('PropList.txt', 'Ideographic')
    complex_context = code_points('LineBreak.txt', 'SA')
    control = code_points('GraphemeBreakProperty.txt', 'Control')

    cls = WORD_CLASSES.index
    values = bytearray(0x110000)
    for c in range(0x110000):
        value = word_break[c]
        kana_kanji = han[c] or hiragana[c] or value == cls('Katakana')
        # ICU's word.txt: $Extend is Word_Break=Extend without Han, and $ALetterPlus is ALetter without the Han, the
        # kana and the Hangul syllables, which its dictionary and the rules after WB13b handle, plus the Complex_Context
        # letters of Thai, Lao, Khmer and Myanmar that are neither Extend nor Control.
        if value == cls('Extend') and han[c]:
            value = cls('Other')
        if 0xAC00 <= c <= 0xD7A3:
            assert value == cls('ALetter'), hex(c)
            value = cls('HangulSyllable')
        elif value == cls('ALetter') and kana_kanji:
            value = cls('Other')
        if complex_context[c] and value != cls('Extend') and not control[c]:
            assert value in (cls('Other'), cls('ALetter')), (hex(c), WORD_CLASSES[value])
            value = cls('ALetter')

        flags = 0
        if extended_pictographic[c]:
            flags |= EXTENDED_PICTOGRAPHIC
        if kana_kanji:
            flags |= KANA_KANJI
        if hiragana[c] or ideographic[c]:
            flags |= IDEOGRAPHIC_OR_HIRAGANA
        # What WordBreaker assumes of the flags: no line break has one; WB4 ignores no Extended_Pictographic and no
        # KanaKanji character, so WB3c and ICU's KanaKanji pairs read them only of the character itself; and an
        # Extended_Pictographic is a letter or nothing, which is all WB3c can join. The one ignorable character with a
        # status of its own is U+16FE4 KHITAN SMALL SCRIPT FILLER (Extend and Ideographic).
        assert not flags or value not in (cls('CR'), cls('LF'), cls('Newline')), hex(c)
        if value in (cls('Extend'), cls('Format'), cls('ZWJ')):
            assert flags & (EXTENDED_PICTOGRAPHIC | KANA_KANJI) == 0, (hex(c), WORD_CLASSES[value], flags)
        if extended_pictographic[c]:
            assert value in (cls('Other'), cls('ALetter')), (hex(c), WORD_CLASSES[value])
        # A KanaKanji character the rules leave Other is joined to the character before it only by ICU's pair rule,
        # which is how WordBreaker.IsWordLike knows which rule ended a word with one.
        if kana_kanji and value == cls('Other'):
            assert not extended_pictographic[c], hex(c)
        assert not kana_kanji or value not in (cls('ZWJ'), cls('WSegSpace'), cls('HangulSyllable')), hex(c)
        values[c] = value | flags

    result = runs(values, 8)
    output = write('WordBreakProperty.txt, emoji-data.txt, Scripts.txt, PropList.txt, LineBreak.txt and GraphemeBreakProperty.txt', 'WordBreaker', '''\
    // The word break properties of every code point, as runs: each entry is the first code point of a run shifted left
    // by eight, with the properties of the whole run in the low eight bits, the WordClass in the low five and the flags
    // above it. A run lasts until the start of the next entry. The classes are the Word_Break property
    // (https://www.unicode.org/reports/tr29/#Word_Break_Property_Values) as ICU's root word rules tailor it.''', result)
    output += '''
    // The same properties for the ASCII characters, read without a search.
    private static ReadOnlySpan<byte> AsciiProperties =>
    [
'''
    output += ascii_table(values)
    output += '''    ];
}
'''
    pathlib.Path('Jint/Native/Intl/WordBreaker.Data.cs').write_text(output, encoding='utf-8', newline='\n')
    print(f'Word_Break: {len(result)} runs')


# The order is the order of GraphemeBreaker.GraphemeClass.
GRAPHEME_CLASSES = [
    'Other', 'CR', 'LF', 'Control', 'Extend', 'ZWJ', 'RegionalIndicator', 'Prepend', 'SpacingMark', 'L', 'V', 'T', 'LV',
    'LVT',
]
GRAPHEME_BREAK_TO_CLASS = {
    'CR': 'CR', 'LF': 'LF', 'Control': 'Control', 'Extend': 'Extend', 'ZWJ': 'ZWJ',
    'Regional_Indicator': 'RegionalIndicator', 'Prepend': 'Prepend', 'SpacingMark': 'SpacingMark',
    'L': 'L', 'V': 'V', 'T': 'T', 'LV': 'LV', 'LVT': 'LVT',
}
# The flags of GraphemeBreaker, above the four bits of the class: Extended_Pictographic, and Indic_Conjunct_Break in two
# bits (None is zero).
GRAPHEME_EXTENDED_PICTOGRAPHIC = 0x10
INDIC_CONJUNCT_BREAK = {'Consonant': 0x20, 'Extend': 0x40, 'Linker': 0x60}


def grapheme():
    grapheme_break = bytearray(0x110000)  # everything not listed is Other (the @missing line of the file)
    seen = set()
    for first, last, name in entries('GraphemeBreakProperty.txt'):
        seen.add(name)
        grapheme_break[first:last + 1] = bytes([GRAPHEME_CLASSES.index(GRAPHEME_BREAK_TO_CLASS[name])]) * (last - first + 1)
    assert seen == set(GRAPHEME_BREAK_TO_CLASS), seen ^ set(GRAPHEME_BREAK_TO_CLASS)

    # Indic_Conjunct_Break is the one enumerated property of DerivedCoreProperties.txt, a line of which reads
    # "094D ; InCB; Linker # ..."; everything not listed is None.
    indic_conjunct_break = bytearray(0x110000)
    seen = set()
    for match in re.finditer(r'^([0-9A-F]+)(?:\.\.([0-9A-F]+))?\s*;\s*InCB\s*;\s*(\w+)', read('DerivedCoreProperties.txt'), re.M):
        first, last, name = int(match.group(1), 16), int(match.group(2) or match.group(1), 16), match.group(3)
        seen.add(name)
        indic_conjunct_break[first:last + 1] = bytes([INDIC_CONJUNCT_BREAK[name]]) * (last - first + 1)
    assert seen == set(INDIC_CONJUNCT_BREAK), seen ^ set(INDIC_CONJUNCT_BREAK)

    extended_pictographic = code_points('emoji-data.txt', 'Extended_Pictographic')

    cls = GRAPHEME_CLASSES.index
    values = bytearray(0x110000)
    for c in range(0x110000):
        value = grapheme_break[c]
        incb = indic_conjunct_break[c]
        # What GraphemeBreaker assumes of the flags: a line break or a control has none, so GB4 and GB5 need not look
        # at them; the characters GB9c reads between two consonants are ones GB9 joins anyway (Extend and ZWJ), and a
        # consonant and an Extended_Pictographic are ordinary characters, so only GB9c and GB11 join them.
        if value in (cls('CR'), cls('LF'), cls('Control')):
            assert not incb and not extended_pictographic[c], hex(c)
        if incb == INDIC_CONJUNCT_BREAK['Linker']:
            assert value == cls('Extend'), (hex(c), GRAPHEME_CLASSES[value])
        elif incb == INDIC_CONJUNCT_BREAK['Extend']:
            assert value in (cls('Extend'), cls('ZWJ')), (hex(c), GRAPHEME_CLASSES[value])
        elif incb == INDIC_CONJUNCT_BREAK['Consonant']:
            assert value == cls('Other'), (hex(c), GRAPHEME_CLASSES[value])
        if extended_pictographic[c]:
            assert value == cls('Other') and not incb, (hex(c), GRAPHEME_CLASSES[value])
            value |= GRAPHEME_EXTENDED_PICTOGRAPHIC
        values[c] = value | incb

    result = runs(values, 8)
    output = write('GraphemeBreakProperty.txt, emoji-data.txt and DerivedCoreProperties.txt', 'GraphemeBreaker', '''\
    // The grapheme cluster break properties of every code point, as runs: each entry is the first code point of a run
    // shifted left by eight, with the properties of the whole run in the low eight bits: the GraphemeClass
    // (https://www.unicode.org/reports/tr29/#Grapheme_Cluster_Break_Property_Values) in the low four, Extended_Pictographic
    // above it, and Indic_Conjunct_Break in the two bits above that. A run lasts until the start of the next entry.''', result)
    output += '''
    // The same properties for the ASCII characters, read without a search.
    private static ReadOnlySpan<byte> AsciiProperties =>
    [
'''
    output += ascii_table(values)
    output += '''    ];
}
'''
    pathlib.Path('Jint/Native/Intl/GraphemeBreaker.Data.cs').write_text(output, encoding='utf-8', newline='\n')
    print(f'Grapheme_Cluster_Break: {len(result)} runs')


grapheme()
sentence()
word()
